#!/usr/bin/env python3
"""Generate the per-area import aggregators and the `TruthCore.lean` root.

Every module under `TruthCore/` except result challenges (`Challenge.lean`,
which state `sorry` goals) belongs to exactly one *area*. Each area has one
generated aggregator module `TruthCore/Imports/<Area>.lean` that imports the
area's modules, one per line, sorted bytewise. `TruthCore.lean` imports only
the aggregators. A PR that adds a module therefore edits only the aggregator
of its own area, and `TruthCore.lean` changes only when an area appears or
disappears. This keeps parallel lanes (AGENTS.md, "Lanes") from conflicting
on one shared import list (#416).

The area of a module is the longest prefix in `AREAS` that contains it;
otherwise its first directory under `TruthCore/`, or the first two for
`TruthCore/Results/<Area>/...`. New top-level directories therefore get an
aggregator automatically; `AREAS` only splits an area further where two lanes
would otherwise share one aggregator.

    scripts/root-imports.sh          check (CI); exits 1 and prints a diff if stale
    scripts/root-imports.sh --write  regenerate the aggregators and TruthCore.lean

`TruthCore/Imports/` is reserved for generated aggregators; do not put
hand-written modules there.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Areas finer than the default, as paths relative to `TruthCore/`. Keep sorted.
# Each line names the lane that owns the area (AGENTS.md, "Lanes"); areas not
# listed fall back to the default rule above.
AREAS = (
    "Case/Catholicism/StageThree",  # lane B: stage 3
    "Greek/NewTestament",  # lane B: New Testament sources
    "Results/Case/Catholicism/StageThree",  # lane B: stage-3 results
    "Results/Comparison/Resurrection",  # lane B: Resurrection comparison results
)

AGGREGATOR_DIR = "Imports"
HEADER = "-- Generated by scripts/root-imports.sh --write; do not edit by hand.\n"


class RootImportsError(Exception):
    pass


def module_name(relative: Path) -> str:
    """`Greek/Plato/Timaeus.lean` -> `TruthCore.Greek.Plato.Timaeus`."""
    return ".".join(("TruthCore",) + relative.with_suffix("").parts)


def area_of(relative: Path, areas: tuple[str, ...] = AREAS) -> str:
    """The area of a module path relative to `TruthCore/`."""
    directories = relative.parent.parts
    if not directories:
        raise RootImportsError(
            f"TruthCore/{relative.as_posix()}: modules directly under TruthCore/ have no area; "
            "put the module in a subdirectory"
        )
    best = ""
    for area in areas:
        parts = tuple(area.split("/"))
        if directories[: len(parts)] == parts and len(area) > len(best):
            best = area
    if best:
        return best
    depth = 2 if directories[0] == "Results" and len(directories) > 1 else 1
    return "/".join(directories[:depth])


def discover(root: Path, areas: tuple[str, ...] = AREAS) -> dict[str, list[str]]:
    """Map each area to its sorted module names."""
    base = root / "TruthCore"
    grouped: dict[str, list[str]] = {}
    for path in base.rglob("*.lean"):
        relative = path.relative_to(base)
        if path.name == "Challenge.lean" or relative.parts[0] == AGGREGATOR_DIR:
            continue
        grouped.setdefault(area_of(relative, areas), []).append(module_name(relative))
    return {area: sorted(modules) for area, modules in grouped.items()}


def aggregator_path(area: str) -> str:
    return f"TruthCore/{AGGREGATOR_DIR}/{area}.lean"


def aggregator_module(area: str) -> str:
    return module_name(Path(AGGREGATOR_DIR, area + ".lean"))


def render(lines: list[str]) -> str:
    return HEADER + "".join(f"import {line}\n" for line in lines)


def expected_files(root: Path, areas: tuple[str, ...] = AREAS) -> dict[str, str]:
    """Repository-relative path -> expected content of every generated file."""
    grouped = discover(root, areas)
    files = {aggregator_path(area): render(modules) for area, modules in grouped.items()}
    files["TruthCore.lean"] = render(sorted(aggregator_module(area) for area in grouped))
    return files


def existing_aggregators(root: Path) -> set[str]:
    directory = root / "TruthCore" / AGGREGATOR_DIR
    if not directory.is_dir():
        return set()
    return {path.relative_to(root).as_posix() for path in directory.rglob("*.lean")}


def stale(root: Path, areas: tuple[str, ...] = AREAS) -> tuple[dict[str, str], list[str]]:
    """Files whose content differs from the expected one, and generated files to delete."""
    expected = expected_files(root, areas)
    changed = {}
    for path, content in expected.items():
        target = root / path
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            changed[path] = content
    removed = sorted(existing_aggregators(root) - set(expected))
    return changed, removed


def write(root: Path, areas: tuple[str, ...] = AREAS) -> None:
    changed, removed = stale(root, areas)
    for path, content in changed.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    for path in removed:
        (root / path).unlink()
    # Drop directories that the removals emptied.
    directory = root / "TruthCore" / AGGREGATOR_DIR
    if directory.is_dir():
        for sub in sorted(directory.rglob("*"), key=lambda p: len(p.parts), reverse=True):
            if sub.is_dir() and not any(sub.iterdir()):
                sub.rmdir()


def check(root: Path, areas: tuple[str, ...] = AREAS) -> list[str]:
    """Return a human-readable diff of every stale file; empty when up to date."""
    changed, removed = stale(root, areas)
    report: list[str] = []
    for path, content in sorted(changed.items()):
        target = root / path
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        report.extend(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=path if target.is_file() else "/dev/null",
                tofile=path,
            )
        )
    for path in removed:
        report.append(f"{path}: no module belongs to this area any more; it must be deleted\n")
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="regenerate the aggregators and TruthCore.lean")
    args = parser.parse_args(argv)
    try:
        if args.write:
            write(ROOT)
            return 0
        report = check(ROOT)
    except RootImportsError as exc:
        print(exc, file=sys.stderr)
        return 1
    if report:
        sys.stdout.writelines(report)
        print("import aggregators are stale: run scripts/root-imports.sh --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
